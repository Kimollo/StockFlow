CREATE SEQUENCE sales_number_seq START WITH 1;

CREATE TABLE sales (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sale_number VARCHAR(20) NOT NULL,
    payment_method VARCHAR(10) NOT NULL,
    status VARCHAR(20) NOT NULL,
    subtotal NUMERIC(12, 2) NOT NULL,
    total NUMERIC(12, 2) NOT NULL,
    sold_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT uq_sales_sale_number UNIQUE (sale_number),
    CONSTRAINT ck_sales_payment_method CHECK (payment_method IN ('CASH', 'CARD', 'EFT')),
    CONSTRAINT ck_sales_status CHECK (status IN ('COMPLETED')),
    CONSTRAINT ck_sales_subtotal_positive CHECK (subtotal > 0),
    CONSTRAINT ck_sales_total_positive CHECK (total > 0)
);

CREATE INDEX idx_sales_sold_at ON sales (sold_at DESC);

CREATE TABLE sale_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sale_id BIGINT NOT NULL,
    product_id BIGINT NOT NULL,
    sku VARCHAR(40) NOT NULL,
    product_name VARCHAR(160) NOT NULL,
    quantity INTEGER NOT NULL,
    unit_price NUMERIC(12, 2) NOT NULL,
    line_total NUMERIC(12, 2) NOT NULL,
    CONSTRAINT fk_sale_items_sale FOREIGN KEY (sale_id) REFERENCES sales (id) ON DELETE RESTRICT,
    CONSTRAINT fk_sale_items_product FOREIGN KEY (product_id) REFERENCES products (id) ON DELETE RESTRICT,
    CONSTRAINT ck_sale_items_sku_not_blank CHECK (length(btrim(sku)) > 0),
    CONSTRAINT ck_sale_items_name_not_blank CHECK (length(btrim(product_name)) > 0),
    CONSTRAINT ck_sale_items_quantity_positive CHECK (quantity > 0),
    CONSTRAINT ck_sale_items_unit_price_positive CHECK (unit_price > 0),
    CONSTRAINT ck_sale_items_line_total_positive CHECK (line_total > 0)
);

CREATE INDEX idx_sale_items_sale_id ON sale_items (sale_id);
CREATE INDEX idx_sale_items_product_id ON sale_items (product_id);

ALTER TABLE stock_movements
    ADD COLUMN sale_id BIGINT,
    ADD CONSTRAINT fk_stock_movements_sale FOREIGN KEY (sale_id) REFERENCES sales (id) ON DELETE RESTRICT,
    ADD CONSTRAINT ck_stock_movements_sale_requires_sale CHECK (
        movement_type <> 'SALE' OR sale_id IS NOT NULL
    );

CREATE INDEX idx_stock_movements_sale_id ON stock_movements (sale_id);
