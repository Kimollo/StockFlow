CREATE TABLE categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(80) NOT NULL,
    CONSTRAINT ck_categories_name_not_blank CHECK (length(btrim(name)) > 0)
);

CREATE UNIQUE INDEX uq_categories_name_lower ON categories (lower(name));

CREATE TABLE products (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku VARCHAR(40) NOT NULL,
    name VARCHAR(160) NOT NULL,
    category_id BIGINT NOT NULL,
    selling_price NUMERIC(12, 2) NOT NULL,
    cost_price NUMERIC(12, 2) NOT NULL,
    stock_quantity INTEGER NOT NULL DEFAULT 0,
    minimum_stock_level INTEGER NOT NULL DEFAULT 0,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT fk_products_category FOREIGN KEY (category_id) REFERENCES categories (id) ON DELETE RESTRICT,
    CONSTRAINT ck_products_sku_not_blank CHECK (length(btrim(sku)) > 0),
    CONSTRAINT ck_products_name_not_blank CHECK (length(btrim(name)) > 0),
    CONSTRAINT ck_products_selling_price_positive CHECK (selling_price > 0),
    CONSTRAINT ck_products_cost_price_non_negative CHECK (cost_price >= 0),
    CONSTRAINT ck_products_stock_non_negative CHECK (stock_quantity >= 0),
    CONSTRAINT ck_products_minimum_stock_non_negative CHECK (minimum_stock_level >= 0)
);

CREATE UNIQUE INDEX uq_products_sku_lower ON products (lower(sku));
CREATE INDEX idx_products_category_id ON products (category_id);
CREATE INDEX idx_products_active_stock ON products (active, stock_quantity);

CREATE TABLE stock_movements (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT NOT NULL,
    movement_type VARCHAR(20) NOT NULL,
    quantity_change INTEGER NOT NULL,
    quantity_after INTEGER NOT NULL,
    reason VARCHAR(255),
    created_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT fk_stock_movements_product FOREIGN KEY (product_id) REFERENCES products (id) ON DELETE RESTRICT,
    CONSTRAINT ck_stock_movements_type CHECK (movement_type IN ('RECEIPT', 'ADJUSTMENT', 'SALE', 'RETURN')),
    CONSTRAINT ck_stock_movements_change_non_zero CHECK (quantity_change <> 0),
    CONSTRAINT ck_stock_movements_quantity_after_non_negative CHECK (quantity_after >= 0),
    CONSTRAINT ck_stock_movements_adjustment_reason CHECK (
        movement_type <> 'ADJUSTMENT' OR (reason IS NOT NULL AND length(btrim(reason)) > 0)
    )
);

CREATE INDEX idx_stock_movements_product_id ON stock_movements (product_id);
CREATE INDEX idx_stock_movements_created_at ON stock_movements (created_at);
