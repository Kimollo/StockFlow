CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(120) NOT NULL,
    username VARCHAR(60) NOT NULL,
    password_hash VARCHAR(100) NOT NULL,
    role VARCHAR(20) NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT ck_users_role CHECK (role IN ('ADMINISTRATOR', 'STAFF'))
);

CREATE UNIQUE INDEX uq_users_username_lower ON users (lower(username));

ALTER TABLE sales
    ADD COLUMN cashier_id BIGINT,
    ADD CONSTRAINT fk_sales_cashier FOREIGN KEY (cashier_id) REFERENCES users (id) ON DELETE RESTRICT;

ALTER TABLE stock_movements
    ADD COLUMN user_id BIGINT,
    ADD CONSTRAINT fk_stock_movements_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE RESTRICT;
